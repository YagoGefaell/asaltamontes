-- T24a: one-time tokens for the account lifecycle (email verification now; password reset and email change in T24b).
-- New table only; nothing that existed before Flyway is touched (BUG-049). Existing users keep is_verified as it is.
-- Only the SHA-256 of the token is stored. A row is deleted when its token is used or replaced, so "used", "replaced"
-- and "unknown" are the same case for the API.

CREATE TABLE account_tokens (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id    bigint       NOT NULL,
    purpose    varchar(20)  NOT NULL,
    token_hash varchar(64)  NOT NULL,
    expires_at timestamp(6) NOT NULL,
    created_at timestamp(6) NOT NULL DEFAULT now(),
    CONSTRAINT pk_account_tokens PRIMARY KEY (id),
    CONSTRAINT uk_account_tokens_hash UNIQUE (token_hash),
    -- One live token per user and purpose: asking for another one replaces the previous
    CONSTRAINT uk_account_tokens_user_purpose UNIQUE (user_id, purpose),
    CONSTRAINT fk_account_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_account_tokens_purpose CHECK (purpose IN ('VERIFY_EMAIL', 'RESET_PASSWORD', 'CHANGE_EMAIL'))
);

-- Cleanup of expired tokens
CREATE INDEX idx_account_tokens_expires ON account_tokens (expires_at);
