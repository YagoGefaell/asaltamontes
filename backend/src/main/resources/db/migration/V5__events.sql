-- T15a: events (meetups, trainings, races, trips) and their attendees.

CREATE TABLE events (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    title              varchar(120)  NOT NULL,
    description        text,
    type               varchar(20)   NOT NULL,
    status             varchar(20)   NOT NULL,
    starts_at          timestamp(6) with time zone NOT NULL,
    ends_at            timestamp(6) with time zone,
    timezone           varchar(40)   NOT NULL,
    meeting_point_name varchar(200),
    latitude           double precision,
    longitude          double precision,
    city               varchar(80),
    distance_km        numeric(5, 1),
    elevation_gain_m   integer,
    level              varchar(20),
    capacity           integer,
    attendee_count     integer       NOT NULL DEFAULT 0,
    visibility         varchar(20)   NOT NULL,
    community_id       bigint,
    organizer_id       bigint        NOT NULL,
    image_url          varchar(255),
    cancel_reason      varchar(500),
    created_at         timestamp(6) with time zone NOT NULL,
    updated_at         timestamp(6) with time zone,
    cancelled_at       timestamp(6) with time zone,
    version            bigint        NOT NULL DEFAULT 0,
    CONSTRAINT pk_events PRIMARY KEY (id),
    CONSTRAINT fk_events_community FOREIGN KEY (community_id) REFERENCES communities (id),
    CONSTRAINT fk_events_organizer FOREIGN KEY (organizer_id) REFERENCES users (id),
    CONSTRAINT ck_events_type CHECK (type IN ('MEETUP', 'TRAINING', 'RACE', 'TRIP')),
    CONSTRAINT ck_events_status CHECK (status IN ('SCHEDULED', 'CANCELLED')),
    CONSTRAINT ck_events_visibility CHECK (visibility IN ('PUBLIC', 'COMMUNITY')),
    CONSTRAINT ck_events_level CHECK (level IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED', 'EXPERT')),
    CONSTRAINT ck_events_community_visibility CHECK (visibility = 'PUBLIC' OR community_id IS NOT NULL),
    CONSTRAINT ck_events_dates CHECK (ends_at IS NULL OR ends_at > starts_at),
    CONSTRAINT ck_events_capacity CHECK (capacity IS NULL OR capacity BETWEEN 1 AND 500),
    CONSTRAINT ck_events_attendee_count CHECK (attendee_count >= 0 AND (capacity IS NULL OR attendee_count <= capacity)),
    CONSTRAINT ck_events_coordinates CHECK (
        (latitude IS NULL AND longitude IS NULL)
        OR (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180))
);

-- Upcoming events (default listing), those of a community, and those of an organizer.
-- City and bounding box filters come with their indexes in T15c.
CREATE INDEX idx_events_starts_at ON events (starts_at, id);
CREATE INDEX idx_events_community_starts_at ON events (community_id, starts_at) WHERE community_id IS NOT NULL;
CREATE INDEX idx_events_organizer ON events (organizer_id);

CREATE TABLE event_attendees (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    event_id          bigint       NOT NULL,
    user_id           bigint       NOT NULL,
    status            varchar(20)  NOT NULL,
    waitlist_position integer,
    joined_at         timestamp(6) with time zone NOT NULL,
    updated_at        timestamp(6) with time zone,
    CONSTRAINT pk_event_attendees PRIMARY KEY (id),
    CONSTRAINT uk_event_attendees_event_user UNIQUE (event_id, user_id),
    CONSTRAINT fk_event_attendees_event FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_event_attendees_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_event_attendees_status CHECK (status IN ('GOING', 'WAITLIST', 'CANCELLED'))
);

-- "My events" (T15c). The attendees of an event use the unique index (event_id first).
CREATE INDEX idx_event_attendees_user_status ON event_attendees (user_id, status);
