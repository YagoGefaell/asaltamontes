-- T23c1: global MODERATOR role and the audit log of administrative actions.
-- users.role already exists since before Flyway: its CHECK is found by definition, not by name (BUG-049; Hibernate
-- named it differently in the environments it created).
DO $$
DECLARE c record;
BEGIN
    FOR c IN SELECT conname FROM pg_constraint
             WHERE conrelid = 'users'::regclass AND contype = 'c' AND pg_get_constraintdef(oid) ILIKE '%role%USER%'
    LOOP
        EXECUTE format('ALTER TABLE users DROP CONSTRAINT %I', c.conname);
    END LOOP;
END $$;
ALTER TABLE users ADD CONSTRAINT ck_users_role CHECK (role IN ('USER', 'MODERATOR', 'ADMIN'));

-- Every action of the panel leaves a row here. actor_id and the target survive the deletion of the accounts
-- (ON DELETE SET NULL), the report keeps its own public id as reference.
CREATE TABLE admin_audit_log (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    public_id         uuid          NOT NULL,
    actor_id          bigint,
    action            varchar(30)   NOT NULL,
    report_id         bigint,
    target_type       varchar(20),
    target_public_id  uuid,
    target_user_id    bigint,
    note              varchar(1000),
    created_at        timestamp(6)  NOT NULL DEFAULT now(),
    CONSTRAINT pk_admin_audit_log PRIMARY KEY (id),
    CONSTRAINT uk_admin_audit_log_public_id UNIQUE (public_id),
    CONSTRAINT fk_admin_audit_actor FOREIGN KEY (actor_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_admin_audit_report FOREIGN KEY (report_id) REFERENCES reports (id) ON DELETE SET NULL,
    CONSTRAINT fk_admin_audit_target_user FOREIGN KEY (target_user_id) REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX idx_admin_audit_created ON admin_audit_log (created_at DESC, id DESC);
-- Purge of the copy kept by resolved reports (details and content_snapshot): by handled date
CREATE INDEX idx_reports_resolved ON reports (handled_at) WHERE status <> 'OPEN' AND (details IS NOT NULL OR content_snapshot IS NOT NULL);
