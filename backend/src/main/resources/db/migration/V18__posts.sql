-- T22a: posts (text with optional photos) in a community or on the author's profile, likes and one-level comments.
-- New tables only; nothing that existed before Flyway is touched (BUG-049).
-- community_id NULL = post on the author's profile (seen by her followers and by herself).
-- Soft delete (deleted_at): every read filters on it, and the indexes are partial on the live rows.

CREATE TABLE posts (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    public_id     uuid         NOT NULL,
    author_id     bigint       NOT NULL,
    community_id  bigint,
    body          text         NOT NULL,
    like_count    bigint       NOT NULL DEFAULT 0,
    comment_count bigint       NOT NULL DEFAULT 0,
    created_at    timestamp(6) NOT NULL DEFAULT now(),
    deleted_at    timestamp(6),
    CONSTRAINT pk_posts PRIMARY KEY (id),
    CONSTRAINT uk_posts_public_id UNIQUE (public_id),
    CONSTRAINT fk_posts_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_posts_community FOREIGN KEY (community_id) REFERENCES communities (id) ON DELETE CASCADE,
    CONSTRAINT ck_posts_body CHECK (char_length(body) BETWEEN 1 AND 2000),
    CONSTRAINT ck_posts_counts CHECK (like_count >= 0 AND comment_count >= 0)
);

-- Keyset pagination (created_at DESC, public_id DESC): public_id is UUID v7, so it also follows creation order,
-- and it is the tie-breaker that the opaque cursor carries.
CREATE INDEX idx_posts_community_created ON posts (community_id, created_at DESC, public_id DESC)
    WHERE deleted_at IS NULL AND community_id IS NOT NULL;
CREATE INDEX idx_posts_author_created ON posts (author_id, created_at DESC, public_id DESC)
    WHERE deleted_at IS NULL;

CREATE TABLE post_media (
    post_id  bigint   NOT NULL,
    position smallint NOT NULL,
    media_id uuid,
    CONSTRAINT pk_post_media PRIMARY KEY (post_id, position),
    CONSTRAINT fk_post_media_post FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_post_media_media FOREIGN KEY (media_id) REFERENCES media (id) ON DELETE SET NULL,
    CONSTRAINT ck_post_media_position CHECK (position BETWEEN 0 AND 3)
);

-- The orphan cleanup and ON DELETE SET NULL look rows up by media id
CREATE INDEX idx_post_media_media ON post_media (media_id) WHERE media_id IS NOT NULL;

CREATE TABLE post_likes (
    post_id    bigint       NOT NULL,
    user_id    bigint       NOT NULL,
    created_at timestamp(6) NOT NULL DEFAULT now(),
    CONSTRAINT pk_post_likes PRIMARY KEY (post_id, user_id),
    CONSTRAINT fk_post_likes_post FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_post_likes_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_post_likes_user ON post_likes (user_id);

CREATE TABLE post_comments (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    public_id  uuid         NOT NULL,
    post_id    bigint       NOT NULL,
    author_id  bigint       NOT NULL,
    body       text         NOT NULL,
    created_at timestamp(6) NOT NULL DEFAULT now(),
    deleted_at timestamp(6),
    CONSTRAINT pk_post_comments PRIMARY KEY (id),
    CONSTRAINT uk_post_comments_public_id UNIQUE (public_id),
    CONSTRAINT fk_post_comments_post FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_post_comments_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_post_comments_body CHECK (char_length(body) BETWEEN 1 AND 1000)
);

CREATE INDEX idx_post_comments_post_created ON post_comments (post_id, created_at, public_id)
    WHERE deleted_at IS NULL;
CREATE INDEX idx_post_comments_author ON post_comments (author_id);
