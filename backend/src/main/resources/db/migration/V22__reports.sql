-- T23b: reports (denuncias) about users, messages, posts, comments, events and communities.
-- New table only; nothing that existed before Flyway is touched (BUG-049).
-- target_id is the internal key of the reported thing and never leaves the backend (D-021); target_public_id is its
-- public id (null for users, who are addressed by username). A reported text is copied into content_snapshot because
-- the original can be deleted. reported_user_id is the author of the content (for the moderation panel, T23c).
-- Reports survive the deletion of the reported account but not of the reporter.

CREATE TABLE reports (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    public_id         uuid          NOT NULL,
    reporter_id       bigint        NOT NULL,
    target_type       varchar(20)   NOT NULL,
    target_id         bigint        NOT NULL,
    target_public_id  uuid,
    reported_user_id  bigint,
    reason            varchar(30)   NOT NULL,
    details           varchar(1000),
    content_snapshot  text,
    status            varchar(20)   NOT NULL DEFAULT 'OPEN',
    handled_by        bigint,
    handled_at        timestamp(6),
    resolution        varchar(1000),
    created_at        timestamp(6)  NOT NULL DEFAULT now(),
    CONSTRAINT pk_reports PRIMARY KEY (id),
    CONSTRAINT uk_reports_public_id UNIQUE (public_id),
    CONSTRAINT fk_reports_reporter FOREIGN KEY (reporter_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_reports_reported_user FOREIGN KEY (reported_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_reports_handled_by FOREIGN KEY (handled_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_reports_target_type CHECK (target_type IN ('USER', 'MESSAGE', 'POST', 'COMMENT', 'EVENT', 'COMMUNITY')),
    CONSTRAINT ck_reports_reason CHECK (reason IN ('SPAM', 'HARASSMENT', 'HATE', 'INAPPROPRIATE', 'DANGEROUS', 'FAKE_ACCOUNT', 'OTHER')),
    CONSTRAINT ck_reports_status CHECK (status IN ('OPEN', 'DISMISSED', 'ACTIONED'))
);

-- One open report per (reporter, target); also what makes a double click or a race safe
CREATE UNIQUE INDEX uk_reports_open_per_target ON reports (reporter_id, target_type, target_id) WHERE status = 'OPEN';
-- Moderation queue (T23c): by status, oldest first
CREATE INDEX idx_reports_queue ON reports (status, created_at, id);
CREATE INDEX idx_reports_reported_user ON reports (reported_user_id) WHERE reported_user_id IS NOT NULL;
