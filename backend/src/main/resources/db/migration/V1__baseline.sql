-- Baseline: the schema that Hibernate (ddl-auto) generated from the entities before Flyway was introduced (T02).
-- Same tables, columns, types and constraints; only the constraint names are explicit instead of generated.
-- Never edit this file once merged: every schema change goes in a new V<n>__description.sql.

CREATE TABLE users (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    username        varchar(50)  NOT NULL,
    password_hash   varchar(100),
    email           varchar(255) NOT NULL,
    role            varchar(10)  NOT NULL,
    is_verified     boolean      NOT NULL,
    created_at      timestamp(6) NOT NULL,
    updated_at      timestamp(6),
    last_connection timestamp(6),
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE user_profiles (
    user_id             bigint       NOT NULL,
    full_name           varchar(255),
    bio                 varchar(500),
    city                varchar(255),
    profile_picture_url varchar(255),
    running_level       varchar(255),
    birth_date          date,
    phone_number        varchar(255),
    followers_count     bigint       NOT NULL,
    following_count     bigint       NOT NULL,
    is_public_profile   boolean      NOT NULL,
    updated_at          timestamp(6),
    CONSTRAINT pk_user_profiles PRIMARY KEY (user_id),
    CONSTRAINT fk_user_profiles_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_user_profiles_running_level CHECK (running_level IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED', 'EXPERT'))
);

CREATE TABLE user_follow (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    follower_id  bigint       NOT NULL,
    following_id bigint       NOT NULL,
    created_at   timestamp(6) NOT NULL,
    CONSTRAINT pk_user_follow PRIMARY KEY (id),
    CONSTRAINT uk_user_follow_follower_following UNIQUE (follower_id, following_id),
    CONSTRAINT fk_user_follow_follower FOREIGN KEY (follower_id) REFERENCES users (id),
    CONSTRAINT fk_user_follow_following FOREIGN KEY (following_id) REFERENCES users (id)
);

CREATE INDEX idx_follower ON user_follow (follower_id);
CREATE INDEX idx_following ON user_follow (following_id);

CREATE TABLE communities (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    name          varchar(100) NOT NULL,
    description   text,
    image_url     varchar(255),
    member_count  bigint       NOT NULL,
    created_by_id bigint       NOT NULL,
    created_at    timestamp(6) NOT NULL,
    updated_at    timestamp(6),
    CONSTRAINT pk_communities PRIMARY KEY (id),
    CONSTRAINT uk_communities_name UNIQUE (name),
    CONSTRAINT fk_communities_created_by FOREIGN KEY (created_by_id) REFERENCES users (id)
);

CREATE TABLE community_members (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    community_id    bigint       NOT NULL,
    user_account_id bigint       NOT NULL,
    role            varchar(20)  NOT NULL,
    status          varchar(20)  NOT NULL,
    joined_at       timestamp(6) NOT NULL,
    CONSTRAINT pk_community_members PRIMARY KEY (id),
    CONSTRAINT uk_community_user UNIQUE (community_id, user_account_id),
    CONSTRAINT fk_community_members_community FOREIGN KEY (community_id) REFERENCES communities (id),
    CONSTRAINT fk_community_members_user FOREIGN KEY (user_account_id) REFERENCES users (id),
    CONSTRAINT ck_community_members_role CHECK (role IN ('OWNER', 'MODERATOR', 'MEMBER')),
    CONSTRAINT ck_community_members_status CHECK (status IN ('ACTIVE', 'MUTED', 'BANNED'))
);

CREATE TABLE conversations (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    chat_type       varchar(255) NOT NULL,
    group_name      varchar(255),
    group_image     varchar(255),
    last_message    varchar(255),
    last_message_at timestamp(6),
    last_sender_id  bigint,
    created_at      timestamp(6) NOT NULL,
    CONSTRAINT pk_conversations PRIMARY KEY (id),
    CONSTRAINT fk_conversations_last_sender FOREIGN KEY (last_sender_id) REFERENCES users (id),
    CONSTRAINT ck_conversations_chat_type CHECK (chat_type IN ('INDIVIDUAL', 'GROUP'))
);

CREATE TABLE conversation_participants (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    conversation_id bigint       NOT NULL,
    user_id         bigint       NOT NULL,
    unread_count    integer      NOT NULL,
    joined_at       timestamp(6) NOT NULL,
    CONSTRAINT pk_conversation_participants PRIMARY KEY (id),
    CONSTRAINT uk_conversation_user UNIQUE (conversation_id, user_id),
    CONSTRAINT fk_conversation_participants_conversation FOREIGN KEY (conversation_id) REFERENCES conversations (id),
    CONSTRAINT fk_conversation_participants_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE messages (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    conversation_id bigint       NOT NULL,
    sender_id       bigint       NOT NULL,
    content         text         NOT NULL,
    sent_at         timestamp(6) NOT NULL,
    CONSTRAINT pk_messages PRIMARY KEY (id),
    CONSTRAINT fk_messages_conversation FOREIGN KEY (conversation_id) REFERENCES conversations (id),
    CONSTRAINT fk_messages_sender FOREIGN KEY (sender_id) REFERENCES users (id)
);
